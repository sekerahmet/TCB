// kod_sabitleri, sözlükteki her kod için Go'da adlı bir sabit üretir
// (pkg/kod/kodlar_uretilmis.go): kod.G100, kod.A001, kod.T503 ... Sabitin adı
// kodun kendisidir, kullanıcıya görünen ad değildir; ad sonradan değişse de Go kodu
// değişmez. Go kodu kodları yalnızca bu sabitlerle yazar (kod.G + 100 biçimi
// kullanılmaz); sözlükte olmayan bir kod yazılırsa derleme düşer.
//
// Üretici kod paketini içe aktarmaz: dil dosyasını (pkg/kod/tr.json) ve dilden
// bağımsız tanımları (pkg/kod/tanim.json) kendisi okur. Böylece üretilen dosya
// eskimiş olsa da üretici çalışır.
//
// Kullanım (depo kökünden):
//
//	go run ./araclar/kod_sabitleri           // dosyayı yeniden yazar
//	go run ./araclar/kod_sabitleri -denetle  // güncel değilse 1 koduyla çıkar
//	go generate ./pkg/kod                 // aynısı
//
// Aynı denetim `go test ./araclar/...` ile de yapılır.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
)

// Depo köküne göre yollar.
var (
	trYolu    = filepath.Join("pkg", "kod", "tr.json")
	tanimYolu = filepath.Join("pkg", "kod", "tanim.json")
	ciktiYolu = filepath.Join("pkg", "kod", "kodlar_uretilmis.go")
)

func main() {
	denetle := flag.Bool("denetle", false, "dosyayı yazma; güncel değilse 1 koduyla çık")
	kok := flag.String("kok", "", "depo kökü (boşsa çalışma klasöründen yukarı doğru go.mod aranır)")
	flag.Parse()

	if *kok == "" {
		*kok = depoKoku()
	}
	yeni, err := Uret(*kok)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Hata: %v\n", err)
		os.Exit(1)
	}
	yol := filepath.Join(*kok, ciktiYolu)
	if *denetle {
		eski, err := os.ReadFile(yol)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Hata: %v\n", err)
			os.Exit(1)
		}
		if !bytes.Equal(bytes.ReplaceAll(eski, []byte("\r\n"), []byte("\n")), yeni) {
			fmt.Fprintf(os.Stderr, "%s güncel değil; go run ./araclar/kod_sabitleri ile yeniden üretin\n", yol)
			os.Exit(1)
		}
		fmt.Printf("%s güncel\n", yol)
		return
	}
	if err := os.WriteFile(yol, yeni, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "Hata: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("%s yazıldı\n", yol)
}

// depoKoku çalışma klasöründen yukarı doğru go.mod'un bulunduğu klasörü arar (go generate
// pkg/kod içinden çalıştırır).
func depoKoku() string {
	d, err := os.Getwd()
	if err != nil {
		return "."
	}
	for {
		if _, err := os.Stat(filepath.Join(d, "go.mod")); err == nil {
			return d
		}
		ust := filepath.Dir(d)
		if ust == d {
			return "."
		}
		d = ust
	}
}

// aileHarfleri pkg/kod'daki sırayla aynıdır (A=1000, G=2000, H=3000 ...).
const aileHarfleri = "AGHTVWY"

type kod struct {
	harf  byte
	sayi  int
	metin string
}

func kodCoz(s string) (kod, error) {
	if len(s) != 4 || bytes.IndexByte([]byte(aileHarfleri), s[0]) < 0 {
		return kod{}, fmt.Errorf("kod %q geçersiz", s)
	}
	n, err := strconv.Atoi(s[1:])
	if err != nil || n <= 0 {
		return kod{}, fmt.Errorf("kod %q geçersiz", s)
	}
	return kod{harf: s[0], sayi: n, metin: s}, nil
}

// trGirdisi dil dosyasındaki bir satırın üreticinin kullandığı alanlarıdır.
type trGirdisi struct {
	Ad string `json:"ad"`
}

// tanimGirdisi tanım dosyasındaki bir satırın üreticinin kullandığı alanlarıdır.
type tanimGirdisi struct {
	Tur     string `json:"tür"`
	Tasindi string `json:"taşındı"`
}

// Uret üretilen Go dosyasının içeriğini verir.
func Uret(kok string) ([]byte, error) {
	trVeri, err := os.ReadFile(filepath.Join(kok, trYolu))
	if err != nil {
		return nil, err
	}
	var tr map[string]trGirdisi
	if err := json.Unmarshal(trVeri, &tr); err != nil {
		return nil, fmt.Errorf("%s: %v", trYolu, err)
	}
	tanimlar := map[string]tanimGirdisi{}
	if veri, err := os.ReadFile(filepath.Join(kok, tanimYolu)); err == nil {
		if err := json.Unmarshal(veri, &tanimlar); err != nil {
			return nil, fmt.Errorf("%s: %v", tanimYolu, err)
		}
	} else if !os.IsNotExist(err) {
		return nil, err
	}

	var kodlar []kod
	for s := range tr {
		k, err := kodCoz(s)
		if err != nil {
			return nil, fmt.Errorf("%s: %v", trYolu, err)
		}
		kodlar = append(kodlar, k)
	}
	sort.Slice(kodlar, func(i, j int) bool {
		if kodlar[i].harf != kodlar[j].harf {
			return bytes.IndexByte([]byte(aileHarfleri), kodlar[i].harf) < bytes.IndexByte([]byte(aileHarfleri), kodlar[j].harf)
		}
		return kodlar[i].sayi < kodlar[j].sayi
	})

	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./araclar/kod_sabitleri; DO NOT EDIT.\n\n")
	b.WriteString("package kod\n\n")
	b.WriteString("// Sözlükteki (tr.json) her canlı kodun adlı sabiti. Sabitin adı kodun kendisidir,\n")
	b.WriteString("// kullanıcıya görünen ad değildir: ad değişse de sabit değişmez. Yorumdaki ad yalnızca\n")
	b.WriteString("// okuyana yardımdır. Taşınan (kaldırılan) kodların sabiti yoktur; bkz. tasinanlar.\n")
	b.WriteString("const (\n")
	var tasinan []kod
	for _, k := range kodlar {
		if tanimlar[k.metin].Tasindi != "" {
			tasinan = append(tasinan, k)
			continue
		}
		fmt.Fprintf(&b, "\t%s Kod = %c + %d // %s\n", k.metin, k.harf, k.sayi, tr[k.metin].Ad)
	}
	b.WriteString(")\n\n")

	b.WriteString("// tasinanlar kaldırılıp işi başka bir koda (başka bir biçime: fonksiyondan metoda ya da\n")
	b.WriteString("// metottan fonksiyona) taşınan kodlardır: eski kod → yeni kod (tanim.json'daki\n")
	b.WriteString("// \"taşındı\" alanı). Eski kodun numarası bir daha kullanılmaz; adı yalnızca hata\n")
	b.WriteString("// mesajında yeni biçimi önermek için dil dosyasında kalır.\n")
	b.WriteString("var tasinanlar = map[Kod]Kod{\n")
	for _, k := range tasinan {
		hedef, err := kodCoz(tanimlar[k.metin].Tasindi)
		if err != nil {
			return nil, fmt.Errorf("%s: %s taşındı: %v", tanimYolu, k.metin, err)
		}
		fmt.Fprintf(&b, "\t%c + %d: %c + %d, // %s → %s\n", k.harf, k.sayi, hedef.harf, hedef.sayi, k.metin, hedef.metin)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
