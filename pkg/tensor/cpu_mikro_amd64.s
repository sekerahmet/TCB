// func sgemm6x16(kb int, ap, bp, c *float32, ldc int)
//
// C[0:6, 0:16] += Σ_k A[k, 0:6]ᵀ · B[k, 0:16]
// Y4..Y15: biriktiriciler (satır r için Y(4+2r) sütun 0-7, Y(5+2r) sütun 8-15)
// Y0, Y1: B satırı; Y2, Y3: yayınlanan A elemanları.
// Döngü ikişer k adımı açılmıştır; tek kalan adım ayrıca işlenir.
TEXT ·sgemm6x16(SB), NOSPLIT, $0-40
	MOVQ kb+0(FP), CX
	MOVQ ap+8(FP), SI
	MOVQ bp+16(FP), DI
	MOVQ c+24(FP), DX
	MOVQ ldc+32(FP), R8
	SHLQ $2, R8

	VXORPS Y4, Y4, Y4
	VXORPS Y5, Y5, Y5
	VXORPS Y6, Y6, Y6
	VXORPS Y7, Y7, Y7
	VXORPS Y8, Y8, Y8
	VXORPS Y9, Y9, Y9
	VXORPS Y10, Y10, Y10
	VXORPS Y11, Y11, Y11
	VXORPS Y12, Y12, Y12
	VXORPS Y13, Y13, Y13
	VXORPS Y14, Y14, Y14
	VXORPS Y15, Y15, Y15

	MOVQ CX, R9
	SHRQ $1, R9
	JZ   tek

ikili:
	VMOVUPS      (DI), Y0
	VMOVUPS      32(DI), Y1
	VBROADCASTSS (SI), Y2
	VBROADCASTSS 4(SI), Y3
	VFMADD231PS  Y0, Y2, Y4
	VFMADD231PS  Y1, Y2, Y5
	VFMADD231PS  Y0, Y3, Y6
	VFMADD231PS  Y1, Y3, Y7
	VBROADCASTSS 8(SI), Y2
	VBROADCASTSS 12(SI), Y3
	VFMADD231PS  Y0, Y2, Y8
	VFMADD231PS  Y1, Y2, Y9
	VFMADD231PS  Y0, Y3, Y10
	VFMADD231PS  Y1, Y3, Y11
	VBROADCASTSS 16(SI), Y2
	VBROADCASTSS 20(SI), Y3
	VFMADD231PS  Y0, Y2, Y12
	VFMADD231PS  Y1, Y2, Y13
	VFMADD231PS  Y0, Y3, Y14
	VFMADD231PS  Y1, Y3, Y15

	VMOVUPS      64(DI), Y0
	VMOVUPS      96(DI), Y1
	VBROADCASTSS 24(SI), Y2
	VBROADCASTSS 28(SI), Y3
	VFMADD231PS  Y0, Y2, Y4
	VFMADD231PS  Y1, Y2, Y5
	VFMADD231PS  Y0, Y3, Y6
	VFMADD231PS  Y1, Y3, Y7
	VBROADCASTSS 32(SI), Y2
	VBROADCASTSS 36(SI), Y3
	VFMADD231PS  Y0, Y2, Y8
	VFMADD231PS  Y1, Y2, Y9
	VFMADD231PS  Y0, Y3, Y10
	VFMADD231PS  Y1, Y3, Y11
	VBROADCASTSS 40(SI), Y2
	VBROADCASTSS 44(SI), Y3
	VFMADD231PS  Y0, Y2, Y12
	VFMADD231PS  Y1, Y2, Y13
	VFMADD231PS  Y0, Y3, Y14
	VFMADD231PS  Y1, Y3, Y15

	ADDQ $48, SI
	ADDQ $128, DI
	DECQ R9
	JNZ  ikili

tek:
	ANDQ $1, CX
	JZ   yaz
	VMOVUPS      (DI), Y0
	VMOVUPS      32(DI), Y1
	VBROADCASTSS (SI), Y2
	VBROADCASTSS 4(SI), Y3
	VFMADD231PS  Y0, Y2, Y4
	VFMADD231PS  Y1, Y2, Y5
	VFMADD231PS  Y0, Y3, Y6
	VFMADD231PS  Y1, Y3, Y7
	VBROADCASTSS 8(SI), Y2
	VBROADCASTSS 12(SI), Y3
	VFMADD231PS  Y0, Y2, Y8
	VFMADD231PS  Y1, Y2, Y9
	VFMADD231PS  Y0, Y3, Y10
	VFMADD231PS  Y1, Y3, Y11
	VBROADCASTSS 16(SI), Y2
	VBROADCASTSS 20(SI), Y3
	VFMADD231PS  Y0, Y2, Y12
	VFMADD231PS  Y1, Y2, Y13
	VFMADD231PS  Y0, Y3, Y14
	VFMADD231PS  Y1, Y3, Y15

yaz:
	VADDPS  (DX), Y4, Y4
	VADDPS  32(DX), Y5, Y5
	VMOVUPS Y4, (DX)
	VMOVUPS Y5, 32(DX)
	ADDQ    R8, DX
	VADDPS  (DX), Y6, Y6
	VADDPS  32(DX), Y7, Y7
	VMOVUPS Y6, (DX)
	VMOVUPS Y7, 32(DX)
	ADDQ    R8, DX
	VADDPS  (DX), Y8, Y8
	VADDPS  32(DX), Y9, Y9
	VMOVUPS Y8, (DX)
	VMOVUPS Y9, 32(DX)
	ADDQ    R8, DX
	VADDPS  (DX), Y10, Y10
	VADDPS  32(DX), Y11, Y11
	VMOVUPS Y10, (DX)
	VMOVUPS Y11, 32(DX)
	ADDQ    R8, DX
	VADDPS  (DX), Y12, Y12
	VADDPS  32(DX), Y13, Y13
	VMOVUPS Y12, (DX)
	VMOVUPS Y13, 32(DX)
	ADDQ    R8, DX
	VADDPS  (DX), Y14, Y14
	VADDPS  32(DX), Y15, Y15
	VMOVUPS Y14, (DX)
	VMOVUPS Y15, 32(DX)
	VZEROUPPER
	RET
