// Kod düzeni standardı (docs/katki.md): küçük dosyalar, kısa fonksiyonlar, Türkçe adlar,
// her pakette görev ve katman belgesi, üretilmiş dosyalarda standart başlık. Bu dosya
// kuralları, duzen_istisnalar_test.go bugünkü istisnaları tutar. İstisna listeleri
// yalnızca küçülebilir: listedeki bir dosya ya da fonksiyon sınırın altına inince
// listeden çıkarılmalıdır, yeni bir kayıt eklenemez (en fazla sayıları sabittir).

const (
	dosyaSiniri     = 600 // el yazımı bir dosyanın en fazla satırı
	fonksiyonSiniri = 80  // test dışı bir fonksiyonun en fazla satırı (func satırından kapanışa)
)

// duzenKokleri Go kodunun bulunduğu klasörlerdir (depo köküne göre).
var duzenKokleri = []string{"cmd", "internal", "lib", "tools"}

// uretilmisBaslik Go'nun üretilmiş dosya başlığıdır (go help generate): araçlar dosyayı bu
// satırdan tanır. Üreteci de söyler: "// Code generated by <üreteç> ...; DO NOT EDIT."
var uretilmisBaslik = regexp.MustCompile(`^// Code generated by \S.* DO NOT EDIT\.$`)

// katmanBelgesi paket belgesinde bulunması gereken katman satırıdır; paket yolunun önekine
// göre seçilir (internal/katman_test.go'daki katmanlarla aynı).
var katmanBelgesi = []struct{ onek, satir string }{
	{"internal/lang/", "Layer: language core (internal/lang)"},
	{"internal/compute/", "Layer: compute core (internal/compute)"},
	{"internal/stdlib", "Layer: standard library (internal/stdlib)"},
	{"internal/devtools/", "Layer: developer tools (internal/devtools)"},
	{"internal/reporoot", "Layer: test helper (internal/reporoot)"},
	{"cmd/", "Layer: command (cmd)"},
	{"lib", "Layer: TR library (lib)"},
	{"tools/", "Layer: tools (tools)"},
}

func kume(s string) map[string]bool {
	m := map[string]bool{}
	for _, w := range strings.Fields(s) {
		m[w] = true
	}
	return m
}

// goDosyasi depodaki bir Go dosyasının düzen denetimi için gereken bilgisidir.
type goDosyasi struct {
	yol      string // depo köküne göre, '/' ile
	satir    int
	test     bool
	uretilen bool
	dosya    *ast.File
	fset     *token.FileSet
}

func goDosyalari(t *testing.T) []goDosyasi {
	t.Helper()
	kok := reporoot.Kok()
	var sonuc []goDosyasi
	for _, k := range duzenKokleri {
		err := filepath.WalkDir(filepath.Join(kok, k), func(yol string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			ad := d.Name()
			if d.IsDir() {
				if atlanan[ad] || strings.HasPrefix(ad, ".") || strings.HasPrefix(ad, "_") {
					return filepath.SkipDir
				}
				return nil
			}
			if !strings.HasSuffix(ad, ".go") {
				return nil
			}
			veri, err := os.ReadFile(yol)
			if err != nil {
				return err
			}
			fset := token.NewFileSet()
			f, err := parser.ParseFile(fset, yol, veri, parser.ParseComments)
			if err != nil {
				return err
			}
			goreli, _ := filepath.Rel(kok, yol)
			sonuc = append(sonuc, goDosyasi{
				yol:      filepath.ToSlash(goreli),
				satir:    strings.Count(string(veri), "\n"),
				test:     strings.HasSuffix(ad, "_test.go"),
				uretilen: uretilmisMi(f),
				dosya:    f,
				fset:     fset,
			})
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	}
	if len(sonuc) < 200 {
		t.Fatalf("yalnızca %d Go dosyası bulundu; depo yapısı değişmiş olabilir", len(sonuc))
	}
	return sonuc
}

// uretilmisMi dosyanın paket satırından önce standart üretilmiş dosya başlığı taşıyıp
// taşımadığını söyler.
func uretilmisMi(f *ast.File) bool {
	for _, g := range f.Comments {
		if g.Pos() > f.Package {
			break
		}
		for _, c := range g.List {
			if uretilmisBaslik.MatchString(c.Text) {
				return true
			}
		}
	}
	return false
}

// Dosya ve klasör adları küçük harf ASCII'dir: harf, rakam ve '_' (Go'nun alışkanlığı;
// kod tabanı İngilizcedir).
func TestDuzenDosyaAdlari(t *testing.T) {
	gecerli := regexp.MustCompile(`^[a-z0-9_]+\.go$`)
	klasor := regexp.MustCompile(`^[a-z0-9_]+$`)
	klasorler := map[string]bool{}
	for _, d := range goDosyalari(t) {
		ad := filepath.Base(d.yol)
		klasorler[filepath.ToSlash(filepath.Dir(d.yol))] = true
		if !gecerli.MatchString(ad) {
			t.Errorf("%s: dosya adı küçük harf ASCII olmalı (harf, rakam, '_')", d.yol)
		}
	}
	for k := range klasorler {
		for _, p := range strings.Split(k, "/") {
			if !klasor.MatchString(p) {
				t.Errorf("%s: klasör adı küçük harf ASCII olmalı (harf, rakam, '_')", k)
			}
		}
	}
}

// Her paketin tek bir paket belgesi vardır; görevini ve katmanını söyler.
func TestDuzenPaketBelgesi(t *testing.T) {
	type paket struct {
		ad      string
		belgeli []string
		belge   string
	}
	paketler := map[string]*paket{}
	for _, d := range goDosyalari(t) {
		if d.test {
			continue
		}
		k := filepath.ToSlash(filepath.Dir(d.yol))
		p := paketler[k]
		if p == nil {
			p = &paket{ad: d.dosya.Name.Name}
			paketler[k] = p
		}
		if d.dosya.Doc != nil {
			p.belgeli = append(p.belgeli, filepath.Base(d.yol))
			p.belge = d.dosya.Doc.Text()
		}
	}
	for k, p := range paketler {
		switch {
		case len(p.belgeli) == 0:
			t.Errorf("%s: paket belgesi yok; paketin ana dosyasına '// Package %s ...' yazın (görev ve katman)", k, p.ad)
			continue
		case len(p.belgeli) > 1:
			t.Errorf("%s: birden çok dosyada paket belgesi var (%s); belge tek dosyada olmalı", k, strings.Join(p.belgeli, ", "))
		}
		if p.ad != "main" && !strings.HasPrefix(p.belge, "Package "+p.ad+" ") && !strings.HasPrefix(p.belge, "Package "+p.ad+", ") {
			t.Errorf("%s: paket belgesi 'Package %s' ile başlamalı", k, p.ad)
		}
		beklenen := ""
		for _, kb := range katmanBelgesi {
			if onekEslesir(k, kb.onek) {
				beklenen = kb.satir
				break
			}
		}
		if beklenen == "" {
			t.Errorf("%s: katmanı bilinmiyor; internal/duzen_test.go katmanBelgesi tablosuna ekleyin", k)
		} else if !strings.Contains(strings.ReplaceAll(p.belge, "\n", " "), beklenen) {
			t.Errorf("%s: paket belgesinde katman satırı yok: %q", k, "// "+beklenen+" ...")
		}
	}
}

// Üretilmiş dosyalar standart başlığı taşır; başlıksız "üretildi" notu kabul edilmez.
func TestDuzenUretilmisBaslik(t *testing.T) {
	eskiNot := regexp.MustCompile(`(?i)ELLE DEĞİŞTİRMEYİN|Kod üretildi|DO NOT EDIT`)
	sayi := 0
	for _, d := range goDosyalari(t) {
		if d.uretilen {
			sayi++
			continue
		}
		if len(d.dosya.Comments) > 0 && d.dosya.Comments[0].Pos() < d.dosya.Package &&
			eskiNot.MatchString(d.dosya.Comments[0].Text()) {
			t.Errorf("%s: üretilmiş dosya başlığı standart değil; ilk satır '// Code generated by <üreteç>; DO NOT EDIT.' olmalı", d.yol)
		}
		if strings.Contains(filepath.Base(d.yol), "uretilmis") {
			t.Errorf("%s: adı üretilmiş diyor ama standart başlığı yok", d.yol)
		}
	}
	if sayi < 4 {
		t.Errorf("yalnızca %d üretilmiş dosya tanındı (en az kod sabitleri ve parca tabloları beklenir)", sayi)
	}
}

// El yazımı dosyalar en fazla dosyaSiniri satırdır; mevcut istisnalar listededir ve büyüyemez.
func TestDuzenDosyaBoyu(t *testing.T) {
	gorulen := map[string]bool{}
	for _, d := range goDosyalari(t) {
		if d.uretilen {
			continue
		}
		ist, listede := buyukDosyalar[d.yol]
		gorulen[d.yol] = listede
		switch {
		case !listede && d.satir > dosyaSiniri:
			t.Errorf("%s: %d satır (sınır %d); dosyayı konularına göre bölün (docs/katki.md)", d.yol, d.satir, dosyaSiniri)
		case listede && d.satir <= dosyaSiniri:
			t.Errorf("%s: artık %d satır; buyukDosyalar listesinden çıkarın (liste yalnızca küçülür)", d.yol, d.satir)
		case listede && d.satir > ist.tavan+duzeltmePayi(ist.tavan):
			t.Errorf("%s: %d satır, istisna tavanı %d (+%d düzeltme payı); büyüyen istisna dosyası bölünmeli", d.yol, d.satir, ist.tavan, duzeltmePayi(ist.tavan))
		}
	}
	istisnaDenetle(t, "buyukDosyalar", len(buyukDosyalar), enFazlaBuyukDosya, gorulen, buyukDosyalar)
}

// Test dışı fonksiyonlar en fazla fonksiyonSiniri satırdır; mevcut istisnalar listededir.
func TestDuzenFonksiyonBoyu(t *testing.T) {
	gorulen := map[string]bool{}
	for _, d := range goDosyalari(t) {
		if d.uretilen || d.test {
			continue
		}
		for _, dcl := range d.dosya.Decls {
			fd, ok := dcl.(*ast.FuncDecl)
			if !ok {
				continue
			}
			n := d.fset.Position(fd.End()).Line - d.fset.Position(fd.Pos()).Line + 1
			anahtar := d.yol + ":" + fonksiyonAdi(fd)
			ist, listede := uzunFonksiyonlar[anahtar]
			if listede {
				gorulen[anahtar] = true
			}
			switch {
			case !listede && n > fonksiyonSiniri:
				t.Errorf("%s: %d satır (sınır %d); fonksiyonu bölün (docs/katki.md)", anahtar, n, fonksiyonSiniri)
			case listede && n <= fonksiyonSiniri:
				t.Errorf("%s: artık %d satır; uzunFonksiyonlar listesinden çıkarın (liste yalnızca küçülür)", anahtar, n)
			case listede && n > ist.tavan+duzeltmePayi(ist.tavan):
				t.Errorf("%s: %d satır, istisna tavanı %d (+%d düzeltme payı); büyüyen istisna fonksiyonu bölünmeli", anahtar, n, ist.tavan, duzeltmePayi(ist.tavan))
			}
		}
	}
	istisnaDenetle(t, "uzunFonksiyonlar", len(uzunFonksiyonlar), enFazlaUzunFonksiyon, gorulen, uzunFonksiyonlar)
}

func fonksiyonAdi(fd *ast.FuncDecl) string {
	if fd.Recv == nil || len(fd.Recv.List) == 0 {
		return fd.Name.Name
	}
	tip := fd.Recv.List[0].Type
	if y, ok := tip.(*ast.StarExpr); ok {
		tip = y.X
	}
	if g, ok := tip.(*ast.IndexExpr); ok {
		tip = g.X
	}
	if id, ok := tip.(*ast.Ident); ok {
		return id.Name + "." + fd.Name.Name
	}
	return fd.Name.Name
}

// istisnaDenetle istisna listesinin sabit üst sınırı aşmadığını, her kaydın gerekçeli
// olduğunu ve artık var olmayan kayıt bulunmadığını denetler.
func istisnaDenetle(t *testing.T, liste string, boy, enFazla int, gorulen map[string]bool, kayitlar map[string]istisna) {
	t.Helper()
	if boy > enFazla {
		t.Errorf("%s: %d kayıt, en fazla %d; istisna listesi büyüyemez", liste, boy, enFazla)
	}
	var yok []string
	for k, ist := range kayitlar {
		if ist.neden == "" {
			t.Errorf("%s: %s kaydının gerekçesi yok", liste, k)
		}
		if !gorulen[k] {
			yok = append(yok, k)
		}
	}
	sort.Strings(yok)
	for _, k := range yok {
		t.Errorf("%s: %s bulunamadı (taşındı ya da silindi); listeden çıkarın", liste, k)
	}
}

// duzeltmePayi bir istisnanın tavanını aşmadan alabileceği küçük büyümedir (tavanın %10'u,
// en az 5 satır): hata düzeltmesi gibi küçük değişiklikler bölmeyi zorunlu kılmasın; kalıcı
// büyüme yine bölmeyi gerektirir.
func duzeltmePayi(tavan int) int {
	if p := tavan / 10; p > 5 {
		return p
	}
	return 5
}
