// Kod düzeni standardı (docs/katki.md): küçük dosyalar, kısa fonksiyonlar, Türkçe adlar,
// her pakette görev ve katman belgesi, üretilmiş dosyalarda standart başlık. Bu dosya
// kuralları, layout_exceptions_test.go bugünkü istisnaları tutar. İstisna listeleri
// yalnızca küçülebilir: listedeki bir dosya ya da fonksiyon sınırın altına inince
// listeden çıkarılmalıdır, yeni bir kayıt eklenemez (en fazla sayıları sabittir).

const (
	fileLimit = 600 // el yazımı bir dosyanın en fazla satırı
	funcLimit = 80  // test dışı bir fonksiyonun en fazla satırı (func satırından kapanışa)
)

// layoutRoots Go kodunun bulunduğu klasörlerdir (depo köküne göre).
var layoutRoots = []string{"cmd", "internal", "lib", "tools"}

// generatedHeader Go'nun üretilmiş dosya başlığıdır (go help generate): araçlar dosyayı bu
// satırdan tanır. Üreteci de söyler: "// Code generated by <üreteç> ...; DO NOT EDIT."
var generatedHeader = regexp.MustCompile(`^// Code generated by \S.* DO NOT EDIT\.$`)

// layerDoc paket belgesinde bulunması gereken katman satırıdır; paket yolunun önekine
// göre seçilir (internal/layers_test.go'daki katmanlarla aynı).
var layerDoc = []struct{ prefix, line string }{
	{"internal/lang/", "Layer: language core (internal/lang)"},
	{"internal/compute/", "Layer: compute core (internal/compute)"},
	{"internal/stdlib", "Layer: standard library (internal/stdlib)"},
	{"internal/devtools/", "Layer: developer tools (internal/devtools)"},
	{"internal/reporoot", "Layer: test helper (internal/reporoot)"},
	{"cmd/", "Layer: command (cmd)"},
	{"lib", "Layer: TR library (lib)"},
	{"tools/", "Layer: tools (tools)"},
}

func set(s string) map[string]bool {
	m := map[string]bool{}
	for _, w := range strings.Fields(s) {
		m[w] = true
	}
	return m
}

// goFile depodaki bir Go dosyasının düzen denetimi için gereken bilgisidir.
type goFile struct {
	path      string // depo köküne göre, '/' ile
	line      int
	test      bool
	generated bool
	file      *ast.File
	fset      *token.FileSet
}

func goFiles(t *testing.T) []goFile {
	t.Helper()
	root := reporoot.Root()
	var result []goFile
	for _, k := range layoutRoots {
		err := filepath.WalkDir(filepath.Join(root, k), func(path string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			name := d.Name()
			if d.IsDir() {
				if skipped[name] || strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") {
					return filepath.SkipDir
				}
				return nil
			}
			if !strings.HasSuffix(name, ".go") {
				return nil
			}
			data, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			fset := token.NewFileSet()
			f, err := parser.ParseFile(fset, path, data, parser.ParseComments)
			if err != nil {
				return err
			}
			rel, _ := filepath.Rel(root, path)
			result = append(result, goFile{
				path:      filepath.ToSlash(rel),
				line:      strings.Count(string(data), "\n"),
				test:      strings.HasSuffix(name, "_test.go"),
				generated: isGenerated(f),
				file:      f,
				fset:      fset,
			})
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	}
	if len(result) < 200 {
		t.Fatalf("yalnızca %d Go dosyası bulundu; depo yapısı değişmiş olabilir", len(result))
	}
	return result
}

// isGenerated dosyanın paket satırından önce standart üretilmiş dosya başlığı taşıyıp
// taşımadığını söyler.
func isGenerated(f *ast.File) bool {
	for _, g := range f.Comments {
		if g.Pos() > f.Package {
			break
		}
		for _, c := range g.List {
			if generatedHeader.MatchString(c.Text) {
				return true
			}
		}
	}
	return false
}

// Dosya ve klasör adları küçük harf ASCII'dir: harf, rakam ve '_' (Go'nun alışkanlığı;
// kod tabanı İngilizcedir).
func TestLayoutFileNames(t *testing.T) {
	valid := regexp.MustCompile(`^[a-z0-9_]+\.go$`)
	dirPattern := regexp.MustCompile(`^[a-z0-9_]+$`)
	dirs := map[string]bool{}
	for _, d := range goFiles(t) {
		name := filepath.Base(d.path)
		dirs[filepath.ToSlash(filepath.Dir(d.path))] = true
		if !valid.MatchString(name) {
			t.Errorf("%s: dosya adı küçük harf ASCII olmalı (harf, rakam, '_')", d.path)
		}
	}
	for k := range dirs {
		for _, p := range strings.Split(k, "/") {
			if !dirPattern.MatchString(p) {
				t.Errorf("%s: klasör adı küçük harf ASCII olmalı (harf, rakam, '_')", k)
			}
		}
	}
}

// Her paketin tek bir paket belgesi vardır; görevini ve katmanını söyler.
func TestLayoutPackageDoc(t *testing.T) {
	type pkg struct {
		name       string
		documented []string
		doc        string
	}
	pkgs := map[string]*pkg{}
	for _, d := range goFiles(t) {
		if d.test {
			continue
		}
		k := filepath.ToSlash(filepath.Dir(d.path))
		p := pkgs[k]
		if p == nil {
			p = &pkg{name: d.file.Name.Name}
			pkgs[k] = p
		}
		if d.file.Doc != nil {
			p.documented = append(p.documented, filepath.Base(d.path))
			p.doc = d.file.Doc.Text()
		}
	}
	for k, p := range pkgs {
		switch {
		case len(p.documented) == 0:
			t.Errorf("%s: paket belgesi yok; paketin ana dosyasına '// Package %s ...' yazın (görev ve katman)", k, p.name)
			continue
		case len(p.documented) > 1:
			t.Errorf("%s: birden çok dosyada paket belgesi var (%s); belge tek dosyada olmalı", k, strings.Join(p.documented, ", "))
		}
		if p.name != "main" && !strings.HasPrefix(p.doc, "Package "+p.name+" ") && !strings.HasPrefix(p.doc, "Package "+p.name+", ") {
			t.Errorf("%s: paket belgesi 'Package %s' ile başlamalı", k, p.name)
		}
		want := ""
		for _, kb := range layerDoc {
			if prefixMatches(k, kb.prefix) {
				want = kb.line
				break
			}
		}
		if want == "" {
			t.Errorf("%s: katmanı bilinmiyor; internal/layout_test.go layerDoc tablosuna ekleyin", k)
		} else if !strings.Contains(strings.ReplaceAll(p.doc, "\n", " "), want) {
			t.Errorf("%s: paket belgesinde katman satırı yok: %q", k, "// "+want+" ...")
		}
	}
}

// Üretilmiş dosyalar standart başlığı taşır; başlıksız "üretildi" notu kabul edilmez.
func TestLayoutGeneratedHeader(t *testing.T) {
	oldNote := regexp.MustCompile(`(?i)ELLE DEĞİŞTİRMEYİN|Kod üretildi|DO NOT EDIT`)
	count := 0
	for _, d := range goFiles(t) {
		if d.generated {
			count++
			continue
		}
		if len(d.file.Comments) > 0 && d.file.Comments[0].Pos() < d.file.Package &&
			oldNote.MatchString(d.file.Comments[0].Text()) {
			t.Errorf("%s: üretilmiş dosya başlığı standart değil; ilk satır '// Code generated by <üreteç>; DO NOT EDIT.' olmalı", d.path)
		}
		if strings.Contains(filepath.Base(d.path), "uretilmis") {
			t.Errorf("%s: adı üretilmiş diyor ama standart başlığı yok", d.path)
		}
	}
	if count < 4 {
		t.Errorf("yalnızca %d üretilmiş dosya tanındı (en az kod sabitleri ve parca tabloları beklenir)", count)
	}
}

// El yazımı dosyalar en fazla fileLimit satırdır; mevcut istisnalar listededir ve büyüyemez.
func TestLayoutFileSize(t *testing.T) {
	visited := map[string]bool{}
	for _, d := range goFiles(t) {
		if d.generated {
			continue
		}
		exc, listed := bigFiles[d.path]
		visited[d.path] = listed
		switch {
		case !listed && d.line > fileLimit:
			t.Errorf("%s: %d satır (sınır %d); dosyayı konularına göre bölün (docs/katki.md)", d.path, d.line, fileLimit)
		case listed && d.line <= fileLimit:
			t.Errorf("%s: artık %d satır; bigFiles listesinden çıkarın (liste yalnızca küçülür)", d.path, d.line)
		case listed && d.line > exc.ceiling+fixMargin(exc.ceiling):
			t.Errorf("%s: %d satır, istisna tavanı %d (+%d düzeltme payı); büyüyen istisna dosyası bölünmeli", d.path, d.line, exc.ceiling, fixMargin(exc.ceiling))
		}
	}
	checkExceptions(t, "bigFiles", len(bigFiles), maxBigFiles, visited, bigFiles)
}

// Test dışı fonksiyonlar en fazla funcLimit satırdır; mevcut istisnalar listededir.
func TestLayoutFuncSize(t *testing.T) {
	visited := map[string]bool{}
	for _, d := range goFiles(t) {
		if d.generated || d.test {
			continue
		}
		for _, dcl := range d.file.Decls {
			fd, ok := dcl.(*ast.FuncDecl)
			if !ok {
				continue
			}
			n := d.fset.Position(fd.End()).Line - d.fset.Position(fd.Pos()).Line + 1
			key := d.path + ":" + funcName(fd)
			exc, listed := longFuncs[key]
			if listed {
				visited[key] = true
			}
			switch {
			case !listed && n > funcLimit:
				t.Errorf("%s: %d satır (sınır %d); fonksiyonu bölün (docs/katki.md)", key, n, funcLimit)
			case listed && n <= funcLimit:
				t.Errorf("%s: artık %d satır; longFuncs listesinden çıkarın (liste yalnızca küçülür)", key, n)
			case listed && n > exc.ceiling+fixMargin(exc.ceiling):
				t.Errorf("%s: %d satır, istisna tavanı %d (+%d düzeltme payı); büyüyen istisna fonksiyonu bölünmeli", key, n, exc.ceiling, fixMargin(exc.ceiling))
			}
		}
	}
	checkExceptions(t, "longFuncs", len(longFuncs), maxLongFuncs, visited, longFuncs)
}

func funcName(fd *ast.FuncDecl) string {
	if fd.Recv == nil || len(fd.Recv.List) == 0 {
		return fd.Name.Name
	}
	kind := fd.Recv.List[0].Type
	if y, ok := kind.(*ast.StarExpr); ok {
		kind = y.X
	}
	if g, ok := kind.(*ast.IndexExpr); ok {
		kind = g.X
	}
	if id, ok := kind.(*ast.Ident); ok {
		return id.Name + "." + fd.Name.Name
	}
	return fd.Name.Name
}

// checkExceptions istisna listesinin sabit üst sınırı aşmadığını, her kaydın gerekçeli
// olduğunu ve artık var olmayan kayıt bulunmadığını denetler.
func checkExceptions(t *testing.T, list string, size, maxCount int, visited map[string]bool, records map[string]exception) {
	t.Helper()
	if size > maxCount {
		t.Errorf("%s: %d kayıt, en fazla %d; istisna listesi büyüyemez", list, size, maxCount)
	}
	var missing []string
	for k, exc := range records {
		if exc.reason == "" {
			t.Errorf("%s: %s kaydının gerekçesi yok", list, k)
		}
		if !visited[k] {
			missing = append(missing, k)
		}
	}
	sort.Strings(missing)
	for _, k := range missing {
		t.Errorf("%s: %s bulunamadı (taşındı ya da silindi); listeden çıkarın", list, k)
	}
}

// fixMargin bir istisnanın tavanını aşmadan alabileceği küçük büyümedir (tavanın %10'u,
// en az 5 satır): hata düzeltmesi gibi küçük değişiklikler bölmeyi zorunlu kılmasın; kalıcı
// büyüme yine bölmeyi gerektirir.
func fixMargin(ceiling int) int {
	if p := ceiling / 10; p > 5 {
		return p
	}
	return 5
}

// testFileRuleRoots are the trees where the test file layout below is enforced. The list grows
// as each layer is cleaned up.
var testFileRuleRoots = []string{"internal/lang/", "internal/compute/", "internal/stdlib/", "internal/devtools/", "cmd/"}

// Test dosyası düzeni (docs/katki.md, "Testler"): üç tür test dosyası vardır.
//   - Birim testi: X_test.go yalnızca X.go'yu sınar ve yanında durur. X_fuzz_test.go ve
//     X_bench_test.go da X.go'ya aittir; X platforma göre bölünmüş olabilir (X_linux.go,
//     X_avx2.go ...).
//   - Davranış testi: behavior_<konu>_test.go birden çok dosyayı kesen bir davranışı sınar
//     (uçtan uca dil anlamı, bütün işlem aileleri boyunca 16 bit ...). Paketin README'sindeki
//     "## Testler" bölümünde "- `behavior_<konu>_test.go`: ne sınadığı" satırıyla anılır.
//   - Ortak yardımcılar: helpers_test.go (TestMain ve paketin testlerinin paylaştığı işlevler).
const (
	behaviorPrefix = "behavior_"
	helpersFile    = "helpers_test.go"
)

// A test file is either a unit test named after the file it tests, a behavior test listed in
// the package README, or the package's shared helpers; a reader finds what a test file covers
// from its name alone.
func TestTestFileMatchesSource(t *testing.T) {
	behaviors := map[string]map[string]bool{} // klasör → davranış dosyaları
	for _, d := range goFiles(t) {
		if !d.test || !inTestRuleScope(d.path) {
			continue
		}
		name := filepath.Base(d.path)
		switch {
		case name == helpersFile:
		case strings.HasPrefix(name, behaviorPrefix):
			dir := filepath.ToSlash(filepath.Dir(d.path))
			if behaviors[dir] == nil {
				behaviors[dir] = map[string]bool{}
			}
			behaviors[dir][name] = true
		default:
			base := strings.TrimSuffix(d.path, "_test.go")
			base = strings.TrimSuffix(strings.TrimSuffix(base, "_fuzz"), "_bench")
			if !hasSource(base) {
				t.Errorf("%s: no %s.go next to it; name the test after the file it tests, move its tests there, "+
					"or (for a behavior across files) name it %s<topic>_test.go and list it in the package README",
					d.path, filepath.Base(base), behaviorPrefix)
			}
		}
	}
	for _, dir := range testPackageDirs(t) {
		listed := readmeBehaviorTests(t, dir)
		for name := range behaviors[dir] {
			if !listed[name] {
				t.Errorf("%s/%s: behavior test not listed in %s/README.md (## Testler: \"- `%s`: what it tests\")", dir, name, dir, name)
			}
		}
		for name := range listed {
			if !behaviors[dir][name] {
				t.Errorf("%s/README.md lists %s, which does not exist", dir, name)
			}
		}
	}
}

func inTestRuleScope(path string) bool {
	for _, r := range testFileRuleRoots {
		if strings.HasPrefix(path, r) {
			return true
		}
	}
	return false
}

// testPackageDirs kurala bağlı ağaçlardaki, test dosyası olan klasörlerdir.
func testPackageDirs(t *testing.T) []string {
	seen := map[string]bool{}
	var dirs []string
	for _, d := range goFiles(t) {
		if dir := filepath.ToSlash(filepath.Dir(d.path)); d.test && inTestRuleScope(d.path) && !seen[dir] {
			seen[dir] = true
			dirs = append(dirs, dir)
		}
	}
	return dirs
}

// behaviorEntry README'nin "## Testler" bölümündeki bir davranış testi satırıdır.
var behaviorEntry = regexp.MustCompile("^- `(" + behaviorPrefix + "[a-z0-9_]+_test\\.go)`: \\S")

// readmeBehaviorTests klasörün README'sindeki "## Testler" bölümünde anılan davranış testleridir.
func readmeBehaviorTests(t *testing.T, dir string) map[string]bool {
	data, err := os.ReadFile(filepath.Join(reporoot.Root(), filepath.FromSlash(dir), "README.md"))
	if err != nil {
		return nil
	}
	listed := map[string]bool{}
	inSection := false
	for _, line := range strings.Split(strings.ReplaceAll(string(data), "\r\n", "\n"), "\n") {
		if strings.HasPrefix(line, "## ") {
			inSection = strings.TrimSpace(line) == "## Testler"
			continue
		}
		if m := behaviorEntry.FindStringSubmatch(line); inSection && m != nil {
			listed[m[1]] = true
		}
	}
	return listed
}

// hasSource reports whether base.go, or a platform variant base_*.go, exists (base is a path
// relative to the repository root, without the .go extension).
func hasSource(base string) bool {
	full := filepath.Join(reporoot.Root(), filepath.FromSlash(base))
	if _, err := os.Stat(full + ".go"); err == nil {
		return true
	}
	variants, _ := filepath.Glob(full + "_*.go")
	for _, v := range variants {
		if !strings.HasSuffix(v, "_test.go") {
			return true
		}
	}
	return false
}
