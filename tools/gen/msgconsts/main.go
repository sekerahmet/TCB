// msgconsts, ileti kataloğundaki her kod için Go'da adlı bir sabit üretir
// (internal/lang/messages/codes_generated.go): messages.H7003 ... Sabitin yanındaki yorum kodun
// Türkçe metnidir (okuyana yardım). Go kodu ileti kodlarını yalnızca bu sabitlerle yazar;
// katalogda olmayan bir kod yazılırsa derleme düşer.
//
// Üretici messages paketini içe aktarmaz: definitions.json ve tr.json'ı kendisi okur. Böylece
// üretilen dosya eskimiş (ya da silinmiş) olsa da üretici çalışır.
//
// Kullanım (depo kökünden):
//
//	go run ./tools/gen/msgconsts           // dosyayı yeniden yazar
//	go run ./tools/gen/msgconsts -denetle  // güncel değilse 1 koduyla çıkar
//	go generate ./internal/lang/messages   // aynısı
//
// Layer: tools (tools); kullanıcıya gitmez.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// Depo köküne göre yollar.
var (
	trPath     = filepath.Join("internal", "lang", "messages", "tr.json")
	outputPath = filepath.Join("internal", "lang", "messages", "codes_generated.go")
)

func main() {
	check := flag.Bool("denetle", false, "dosyayı yazma; güncel değilse 1 koduyla çık")
	root := flag.String("kok", "", "depo kökü (boşsa çalışma klasöründen yukarı doğru go.mod aranır)")
	flag.Parse()
	if *root == "" {
		*root = repoRoot()
	}
	fresh, err := Generate(*root)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Hata: %v\n", err)
		os.Exit(1)
	}
	path := filepath.Join(*root, outputPath)
	if *check {
		old, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(old, fresh) {
			fmt.Fprintf(os.Stderr, "%s güncel değil: go run ./tools/gen/msgconsts\n", outputPath)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(path, fresh, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "Hata: %v\n", err)
		os.Exit(1)
	}
}

// Generate üretilecek dosyanın içeriğini verir.
func Generate(root string) ([]byte, error) {
	data, err := os.ReadFile(filepath.Join(root, trPath))
	if err != nil {
		return nil, err
	}
	keys, texts, err := orderedTexts(data)
	if err != nil {
		return nil, fmt.Errorf("%s: %v", trPath, err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./tools/gen/msgconsts; DO NOT EDIT.\n\n")
	b.WriteString("package messages\n\n")
	b.WriteString("// İleti kodları (tr.json); her sabitin yorumu Türkçe metnidir.\n")
	b.WriteString("const (\n")
	for _, k := range keys {
		n, err := strconv.Atoi(k[1:])
		if len(k) != 5 || k[0] != 'H' || err != nil {
			return nil, fmt.Errorf("%s: ileti kodu %q geçersiz", trPath, k)
		}
		// Yorum tek satırdır: metindeki satır sonu kaçırılır.
		comment := strings.NewReplacer("\r", `\r`, "\n", `\n`).Replace(texts[k])
		fmt.Fprintf(&b, "\t%s Code = %d // %s\n", k, n, comment)
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

// orderedTexts dil dosyasının kodlarını dosyadaki sırayla ve metinleriyle verir.
func orderedTexts(data []byte) ([]string, map[string]string, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	if _, err := dec.Token(); err != nil {
		return nil, nil, err
	}
	var keys []string
	texts := map[string]string{}
	for dec.More() {
		t, err := dec.Token()
		if err != nil {
			return nil, nil, err
		}
		k, _ := t.(string)
		var text string
		if err := dec.Decode(&text); err != nil {
			return nil, nil, err
		}
		keys = append(keys, k)
		texts[k] = text
	}
	return keys, texts, nil
}

// repoRoot çalışma klasöründen yukarı doğru go.mod'un bulunduğu ilk klasördür.
func repoRoot() string {
	dir, err := os.Getwd()
	if err != nil {
		return "."
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "."
		}
		dir = parent
	}
}
